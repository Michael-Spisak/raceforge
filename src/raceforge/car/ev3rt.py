"""EV3RT 1.1 bridge app: configure, build and upload (spec 0011).

The C sources live in ``ev3rt/`` (``common/`` shared library, ``apps/raceforge_bridge/`` the EV3RT
app). :func:`build` copies them into the EV3RT SDK's workspace together with an ``rf_config.h``
generated from the car bundle's ``ev3`` section and runs EV3RT's own ``make app=raceforge_bridge``.
:func:`upload` sends the resulting ``app`` file to the EV3RT loader over Bluetooth PAN, exactly like
EV3RT's ``make upload``.
"""

import os
import shutil
import subprocess
from collections.abc import Callable, Sequence
from pathlib import Path

import httpx

from raceforge.car.bundle import Ev3Gains, Ev3Spec

APP = "raceforge_bridge"
DEFAULT_IP = "10.0.10.1"  # EV3RT's Bluetooth PAN address (NAP mode)
REPO_EV3RT = Path(__file__).resolve().parents[3] / "ev3rt"

_MOTOR = {"A": 0, "B": 1, "C": 2, "D": 3}
_LINK = {"uart": "EV3_SERIAL_UART", "bt_spp": "EV3_SERIAL_BT"}

Runner = Callable[[Sequence[str], Path], int]


class Ev3rtError(RuntimeError):
    pass


def sensor_kinds(ev3: Ev3Spec) -> list[str]:
    """RF_SENSOR_* name for ports 1..4."""
    kinds = ["RF_SENSOR_NONE"] * 4
    for port in ev3.ultrasonic.values():
        kinds[int(port) - 1] = "RF_SENSOR_ULTRASONIC"
    if ev3.gyro and ev3.gyro_port:
        kinds[int(ev3.gyro_port) - 1] = "RF_SENSOR_GYRO"
    for touch in (ev3.estop_touch_port, ev3.start_touch_port):
        if touch:
            kinds[int(touch) - 1] = "RF_SENSOR_TOUCH"
    return kinds


def _f(x: float) -> str:
    """C float literal (repr always has a '.' or an exponent)."""
    return f"{float(x)!r}f"


def config_header(ev3: Ev3Spec, steer_medium: bool = True) -> str:
    """``rf_config.h`` for the EV3RT bridge app from the bundle's EV3 section."""
    if ev3.os != "ev3rt":
        raise Ev3rtError('bundle ev3.os is not "ev3rt"')
    g = ev3.gains or Ev3Gains()
    kinds = sensor_kinds(ev3)
    estop = int(ev3.estop_touch_port) - 1 if ev3.estop_touch_port else -1
    lines = [
        "/* Generated by `raceforge car ev3rt build` from the car bundle (spec 0011). */",
        "#ifndef RF_CONFIG_H",
        "#define RF_CONFIG_H",
        "",
        "#define RF_CONTROL_PERIOD_MS 10",
        f"#define RF_LINK_PORT {_LINK[ev3.link]}",
        f"#define RF_STEER_PORT {_MOTOR[ev3.steer_motor]} /* {ev3.steer_motor} */",
        f"#define RF_DRIVE_PORT {_MOTOR[ev3.drive_motor]} /* {ev3.drive_motor} */",
        f"#define RF_STEER_MOTOR {'MEDIUM_MOTOR' if steer_medium else 'LARGE_MOTOR'}",
        "#define RF_DRIVE_MOTOR LARGE_MOTOR",
        *[f"#define RF_SENSOR_{i + 1} {k}" for i, k in enumerate(kinds)],
        f"#define RF_ESTOP_TOUCH_PORT ({estop})",
        "#define RF_FAILSAFE_MS 150",
        "",
        f"#define RF_DRIVE_FF {_f(g.drive_ff)}",
        f"#define RF_DRIVE_KP {_f(g.drive_kp)}",
        f"#define RF_DRIVE_KI {_f(g.drive_ki)}",
        f"#define RF_STEER_KP {_f(g.steer_kp)}",
        f"#define RF_STEER_MIN_POWER {g.steer_min_power}",
        f"#define RF_STEER_MAX_POWER {g.steer_max_power}",
        f"#define RF_STEER_DEADBAND_DEG {g.steer_deadband_deg}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def rc_conf(ev3: Ev3Spec) -> str:
    """Settings the brick's ``/ev3rt/etc/rc.conf.ini`` needs for this link (comments on their own
    lines: EV3RT's INI reader keeps text after a value)."""
    lines = ["[Debug]", "; keep log output off the link", "DefaultPort=LCD"]
    if ev3.link == "uart":
        lines += ["", "[Sensors]", "; sensor port 1 becomes the UART link", "DisablePort1=1"]
    if ev3.link == "bt_spp":
        lines += ["", "[Bluetooth]", "; bench tests only, never in race mode", "TurnOff=0"]
    return "\n".join(lines) + "\n"


DEFAULT_SDK = Path.home() / "ev3rt" / "hrp3" / "sdk"
# EV3RT 1.1 links cfg1_out.c into an executable and then links that executable again; binutils
# >= 2.40 refuses ("cannot use executable file as input to a link"). An object file is equivalent.
_LUM = Path("target/ev3_gcc/dmloader/app/Makefile.lum")
_LUM_OLD = "@$(CFGLINK) $(CFLAGS) -Wl,-e,0 -o cfg1_out.o cfg1_out.c"
_LUM_NEW = "@$(CFGLINK) $(CFLAGS) -c -o cfg1_out.o cfg1_out.c"


def find_sdk(explicit: str | None = None) -> Path:
    """``--sdk``, ``$RF_EV3RT_SDK`` or ``~/ev3rt/hrp3/sdk`` (where ``setup-sdk`` unpacks it)."""
    raw = explicit or os.environ.get("RF_EV3RT_SDK")
    sdk = Path(raw).expanduser() if raw else DEFAULT_SDK
    if not (sdk / "workspace" / "Makefile").is_file():
        raise Ev3rtError(
            f"no EV3RT SDK at {sdk}: run `raceforge car ev3rt setup-sdk --release <folder>` "
            "(the unpacked EV3RT 1.1 release) or give --sdk"
        )
    return sdk


def patch_sdk(sdk: Path) -> bool:
    """Make the EV3RT 1.1 SDK build with current Arm GNU toolchains; True if a file was changed."""
    lum = sdk.parent / _LUM
    if not lum.is_file():
        raise Ev3rtError(f"{lum} missing: is {sdk} the 'sdk' folder of EV3RT 1.1 (HRP3)?")
    text = lum.read_text(encoding="utf-8")
    if _LUM_OLD not in text:
        return False
    lum.write_text(text.replace(_LUM_OLD, _LUM_NEW), encoding="utf-8")
    return True


def setup_sdk(release: Path, dest: Path = DEFAULT_SDK.parent.parent) -> Path:
    """Unpack ``hrp3.tar.xz`` of the EV3RT 1.1 release to ``dest`` and patch it; returns the SDK."""
    import tarfile

    archive = release / "hrp3.tar.xz"
    if not archive.is_file():
        raise Ev3rtError(f"{archive} missing: give the unpacked EV3RT 1.1 release folder")
    dest.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive) as tar:
        tar.extractall(dest, filter="data")
    sdk = dest / "hrp3" / "sdk"
    patch_sdk(sdk)
    return sdk


def install(app_file: Path, volume: Path, name: str = APP) -> Path:
    """Copy the app to the brick's SD card mounted over USB (``/Volumes/…`` on macOS).

    EV3RT shows the SD card as a USB drive while the loader runs; apps live in ``ev3rt/apps/``.
    """
    apps = volume / "ev3rt" / "apps"
    if not apps.is_dir():
        raise Ev3rtError(
            f"{apps} not found: connect the EV3 (running EV3RT) by USB and give its drive "
            "(e.g. /Volumes/EV3RT), or copy the SD card's ev3rt folder first"
        )
    target = apps / name
    shutil.copyfile(app_file, target)
    return target


def stage(sdk: Path, ev3: Ev3Spec, source: Path = REPO_EV3RT) -> Path:
    """Copy app, shared library and generated config to ``<sdk>/workspace/raceforge_bridge``."""
    workspace = sdk / "workspace"
    if not (workspace / "Makefile").is_file():
        raise Ev3rtError(f"{sdk} does not look like an EV3RT SDK (missing workspace/Makefile)")
    target = workspace / APP
    if target.exists():
        shutil.rmtree(target)
    target.mkdir()
    for f in sorted((source / "apps" / APP).iterdir()):
        if f.is_file() and f.name != "rf_config.h":
            shutil.copyfile(f, target / f.name)
    for f in sorted((source / "common").iterdir()):
        if f.suffix in (".c", ".h"):
            shutil.copyfile(f, target / f.name)
    (target / "rf_config.h").write_text(config_header(ev3), encoding="utf-8")
    return target


def toolchain_bin() -> Path | None:
    """Folder with ``arm-none-eabi-gcc``: ``$RF_ARM_TOOLCHAIN``, the PATH or the user install
    ``~/.local/arm-gnu-toolchain`` (Arm GNU toolchain unpacked without admin rights)."""
    env = os.environ.get("RF_ARM_TOOLCHAIN")
    candidates = [Path(env) / "bin", Path(env)] if env else []
    found = shutil.which("arm-none-eabi-gcc")
    if found:
        candidates.append(Path(found).parent)
    candidates.append(Path.home() / ".local" / "arm-gnu-toolchain" / "bin")
    return next((c for c in candidates if (c / "arm-none-eabi-gcc").is_file()), None)


def _run(cmd: Sequence[str], cwd: Path) -> int:
    env = dict(os.environ, PWD=str(cwd))  # EV3RT's makefiles use $(PWD), not the real cwd
    tools = toolchain_bin()
    if tools is None:
        raise Ev3rtError(
            "arm-none-eabi-gcc not found: install the Arm GNU toolchain (arm-none-eabi) and put it "
            "on the PATH, set RF_ARM_TOOLCHAIN, or unpack it to ~/.local/arm-gnu-toolchain"
        )
    env["PATH"] = f"{tools}{os.pathsep}{env.get('PATH', '')}"
    return subprocess.run(list(cmd), cwd=cwd, env=env, check=False).returncode


def build(sdk: Path, ev3: Ev3Spec, runner: Runner = _run, source: Path = REPO_EV3RT) -> Path:
    """Stage and run EV3RT's ``make app=raceforge_bridge``; returns the built ``app`` file."""
    stage(sdk, ev3, source)
    patch_sdk(sdk)
    workspace = sdk / "workspace"
    code = runner(["make", f"app={APP}"], workspace)
    app = workspace / "app"
    if code != 0 or not app.is_file():
        raise Ev3rtError(f"EV3RT build failed (make exit code {code}); see the output above")
    return app


def upload(
    app_file: Path,
    ip: str = DEFAULT_IP,
    name: str = APP,
    client: httpx.Client | None = None,
) -> None:
    """Send the app to the EV3RT loader over Bluetooth PAN (same request as EV3RT's ``make
    upload``).
    """
    owned = client is None
    http = client or httpx.Client(timeout=30, trust_env=False)
    try:
        r = http.post(
            f"http://{ip}/upload",
            content=app_file.read_bytes(),
            headers={
                "Content-Type": "ev3rt/app",
                "Content-Disposition": f'inline; filename="{name}"',
            },
        )
    except httpx.TransportError as exc:
        raise Ev3rtError(
            f"EV3 not reachable at {ip}: connect this computer to the brick over Bluetooth PAN "
            "and start the EV3RT loader on the brick"
        ) from exc
    finally:
        if owned:
            http.close()
    if r.status_code >= 400:
        raise Ev3rtError(f"EV3RT loader refused the upload: HTTP {r.status_code}")
