@pytest.mark.skipif(CC is None, reason="no C compiler")
def test_generated_config_compiles_with_the_app(tmp_path: Path) -> None:
    """The header Python writes is what app.c expects (checked against the stub EV3RT API)."""
    inc = tmp_path / "inc"
    inc.mkdir()
    (inc / "rf_config.h").write_text(
        ev3rt.config_header(ev3rt_spec(estop_touch_port="1", link="usb_cdc"))
    )
    r = subprocess.run(
        [
            CC or "cc",
            "-std=c99",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-fsyntax-only",
            f"-I{inc}",
            f"-I{ROOT / 'ev3rt' / 'tests' / 'stub'}",
            f"-I{ROOT / 'ev3rt' / 'common'}",
            str(ROOT / "ev3rt" / "apps" / "raceforge_bridge" / "app.c"),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert r.returncode == 0, r.stderr
